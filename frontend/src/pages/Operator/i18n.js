const DICTS = { uz, ru, en };

export const translate = (lang, key) => DICTS[lang]?.[key] ?? uz[key] ?? key;

/** const t = useT(); t('menu.orders') */
export function useT() {
  const lang = useOperator()?.prefs.lang ?? 'uz';
  const t = (key) => translate(lang, key);
  t.lang = lang;
  t.locale = LOCALES[lang] ?? LOCALES.uz;
  return t;
}
