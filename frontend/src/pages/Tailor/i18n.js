const DICTS = { uz, ru };

// t('ws.footer', { total: 5 }) — {total} o'rniga qiymat qo'yiladi
export const translate = (lang, key, vars) => {
  const text = DICTS[lang]?.[key] ?? uz[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : text;
};

/** const t = useT(); t('nav.queue') */
export function useT() {
  const ctx = useTailor();
  const lang = ctx?.prefs.lang ?? 'uz';
  // `t` lang o'zgarmaguncha barqaror bo'lishi kerak (useCallback deps uchun)
  const t = useCallback((key, vars) => translate(lang, key, vars), [lang]);
  t.lang = lang;
  t.locale = LOCALES[lang] ?? LOCALES.uz;
  return t;
}

