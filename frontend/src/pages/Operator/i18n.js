const DICTS = { uz, ru, en };

// t('fac.total', { n: 5 }) — {n} o'rniga qiymat qo'yiladi
export const translate = (lang, key, vars) => {
  const text = DICTS[lang]?.[key] ?? uz[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : text;
};

/** const t = useT(); t('menu.orders') */
export function useT() {
  const lang = useOperator()?.prefs.lang ?? 'uz';
  const t = (key, vars) => translate(lang, key, vars);
  t.lang = lang;
  t.locale = LOCALES[lang] ?? LOCALES.uz;
  return t;
}
